#!/usr/bin/env python3
"""
make_skin_sss_kernel.py - write gamedata/shaders/r3/skin_sss_kernel.h, the blur kernels of the
screen-space skin subsurface scattering (skin_sss.h, r4_rendertarget_phase_skin_sss.cpp).

The kernel is Jorge Jimenez's separable subsurface scattering kernel ("Separable Subsurface
Scattering", Jimenez, Zsolnai, Jarabo, Freude, Auzinger, Wu, von der Pahlen, Wimmer, Gutierrez,
Computer Graphics Forum 2015; SeparableSSS.cpp of his demo, calculateKernel()): a 1D cut through
the skin diffusion profile of d'Eon & Luebke (a sum of five Gaussians, the narrowest one left out:
that light is the "strength" below), sampled at offsets that bunch up near the centre, weighted by
the area each sample covers, normalised per colour channel, then mixed with the unblurred centre by
the per-channel strength. Red scatters furthest (falloff), which is what gives skin its soft, warm
shadow edges.

One kernel per tap count is written; the shader picks one with SKIN_SSS_TAPS (skin_sss.h).
Each entry is float4( weight r, g, b, offset ): offset in units of the scatter width, entry 0 is
the centre (offset 0).

Usage
  python make_skin_sss_kernel.py [--out gamedata/shaders/r3/skin_sss_kernel.h] [--dry-run]
  --dry-run prints the kernels and their sums instead of writing the file.

Caveats
  - The profile is Jimenez's skin profile. Other materials (wax, marble, leaves) need another
    profile; only FALLOFF / STRENGTH are exposed here.
  - Fewer taps alias at large widths (visible as faint copies of shadow edges); 25 taps covers
    3 widths (Jimenez: RANGE 3 above 20 samples, 2 below), 11 and 17 cover 2.
  - The header is generated: edit the settings below and run the tool again rather than editing
    the header by hand.
"""

import argparse
import math
import os
import sys

# ------------------------------------------------------------------------------------------
# Settings
# ------------------------------------------------------------------------------------------

# How far each channel scatters, relative to the width (Jimenez's demo: 1.0, 0.37, 0.3)
FALLOFF = (1.00, 0.37, 0.30)
# How much of each channel is scattered at all; the rest stays at the centre pixel
# (Jimenez's demo: 0.48, 0.41, 0.28)
STRENGTH = (0.48, 0.41, 0.28)
# Kernels written (odd counts; the shader's SKIN_SSS_TAPS must be one of them)
TAP_COUNTS = (11, 17, 25)
# Offset spacing: 2 = samples bunched near the centre (Jimenez)
EXPONENT = 2.0

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.join(HERE, "..", "gamedata", "shaders", "r3", "skin_sss_kernel.h")

# ------------------------------------------------------------------------------------------


def gaussian(variance, r):
    out = []
    for f in FALLOFF:
        rr = r / (0.001 + f)
        out.append(math.exp(-(rr * rr) / (2.0 * variance)) / (2.0 * 3.14 * variance))
    return out


def profile(r):
    # 0.233 * gaussian(0.0064, r) is the directly bounced light, handled by STRENGTH
    terms = ((0.100, 0.0484), (0.118, 0.187), (0.113, 0.567), (0.358, 1.99), (0.078, 7.41))
    acc = [0.0, 0.0, 0.0]
    for w, v in terms:
        g = gaussian(v, r)
        for i in range(3):
            acc[i] += w * g[i]
    return acc


def kernel(n):
    rng = 3.0 if n > 20 else 2.0
    step = 2.0 * rng / (n - 1)
    off = []
    for i in range(n):
        o = -rng + i * step
        sign = -1.0 if o < 0.0 else 1.0
        off.append(rng * sign * abs(o ** EXPONENT) / rng ** EXPONENT)
    k = []
    for i in range(n):
        w0 = abs(off[i] - off[i - 1]) if i > 0 else 0.0
        w1 = abs(off[i] - off[i + 1]) if i < n - 1 else 0.0
        area = (w0 + w1) / 2.0
        p = profile(off[i])
        k.append([area * p[0], area * p[1], area * p[2], off[i]])
    c = k.pop(n // 2)            # the centre (offset 0) first
    k.insert(0, c)
    s = [sum(e[i] for e in k) for i in range(3)]
    for e in k:
        for i in range(3):
            e[i] /= s[i]
    for i in range(3):
        k[0][i] = (1.0 - STRENGTH[i]) + STRENGTH[i] * k[0][i]
        for e in k[1:]:
            e[i] *= STRENGTH[i]
    return k


def render():
    lines = [
        "// Generated by tools/make_skin_sss_kernel.py - edit the settings there and run it again.",
        "// Jimenez separable SSS kernel (SeparableSSS.cpp, calculateKernel): float4( weight rgb, offset ),",
        "// offset in scatter widths, entry 0 = centre.",
        f"// FALLOFF  = {FALLOFF}",
        f"// STRENGTH = {STRENGTH}",
        "#ifndef SKIN_SSS_KERNEL_H",
        "#define SKIN_SSS_KERNEL_H",
        "",
    ]
    first = True
    for n in TAP_COUNTS:
        k = kernel(n)
        lines.append(f"#{'if' if first else 'elif'} SKIN_SSS_TAPS == {n}")
        first = False
        lines.append(f"static const float4 skin_sss_kernel[{n}] =")
        lines.append("{")
        for e in k:
            lines.append(f"\tfloat4( {e[0]:.6f}, {e[1]:.6f}, {e[2]:.6f}, {e[3]:+.6f} ),")
        lines[-1] = lines[-1].rstrip(",")
        lines.append("};")
    lines += ["#else", "#\terror SKIN_SSS_TAPS must be one of " + ", ".join(map(str, TAP_COUNTS)) +
              " (tools/make_skin_sss_kernel.py)", "#endif", "", "#endif", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    for n in TAP_COUNTS:
        if n % 2 == 0 or n < 3:
            sys.exit(f"error: TAP_COUNTS: {n} is not an odd count >= 3")
    if a.dry_run:
        for n in TAP_COUNTS:
            k = kernel(n)
            sums = [sum(e[i] for e in k) for i in range(3)]
            print(f"{n} taps: sums {sums[0]:.4f} {sums[1]:.4f} {sums[2]:.4f}, centre "
                  f"{k[0][0]:.3f} {k[0][1]:.3f} {k[0][2]:.3f}, offsets {min(e[3] for e in k):+.2f}..{max(e[3] for e in k):+.2f}")
        print(f"[dry-run] would write {os.path.normpath(a.out)}")
        return 0
    with open(a.out, "w", newline="") as f:
        f.write(render())
    print("wrote", os.path.normpath(a.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
